@triton.jit
def _convert_to_uint32(x):
    bits = x.to(tl.uint32, bitcast=True)
    sign_mask = tl.full(bits.shape, 0x80000000, tl.uint32)
    sign_set = (bits & sign_mask) != 0
    inv = (~bits) & tl.full(bits.shape, 0x7FFFFFFF, tl.uint32)
    return tl.where(sign_set, bits, inv)


@triton.jit
def _extract_bin_idx(x, in_range, pattern, STEP: tl.constexpr):
    is_partial_match = in_range
    if STEP == 0:
        h = x.to(tl.float16)
        bits = h.to(tl.uint16, bitcast=True)
        sign_mask = tl.full(bits.shape, 0x8000, tl.uint16)
        sign_set = (bits & sign_mask) != 0
        inv = (~bits) & tl.full(bits.shape, 0x7FFF, tl.uint16)
        mapped = tl.where(sign_set, bits, inv)
        bin_idx = (mapped >> 5).to(tl.uint32)
    else:
        bits = _convert_to_uint32(x)
        if STEP == 1:
            bin_idx = bits >> 21
        elif STEP == 2:
            bin_idx = (bits >> 10) & 0x7FF
            is_partial_match &= ((bits ^ pattern) >> 21) == 0
        elif STEP == 3:
            bin_idx = bits & 0x3FF
            is_partial_match &= ((bits ^ pattern) >> 10) == 0
    return bin_idx, is_partial_match


@triton.jit
def _distribute_to_bins(
    logits,
    in_range,
    ones,
    logit_pattern,
    s_histogram_ptr,
    STEP: tl.constexpr,
):
    bin_idx, is_partial_match = _extract_bin_idx(
        logits,
        in_range,
        logit_pattern,
        STEP=STEP,
    )
    tl.atomic_add(
        s_histogram_ptr + bin_idx,
        ones,
        mask=is_partial_match,
        sem="relaxed",
        scope="cta",
    )


@triton.jit
def _stable_output_positions(base, mask):
    # The row-owning CTA carries its counter through the scan in registers.
    counts = tl.reshape(mask.to(tl.int32), (mask.numel,))
    positions = base + tl.cumsum(counts, axis=0) - 1
    return tl.reshape(positions, mask.shape), base + tl.sum(counts, axis=0)


@triton.jit
def _process_bins(
    logits,
    in_range,
    ones,
    offs,  # row_start based
    found_topk_values_ptrs,
    final_cnt_ptrs,
    logit_pattern,
    threshold_bin_idx,
    write_directly,
    use_final,
    row_start,
    indices_ptr,
    s_histogram_ptr,
    s_final_logits_ptr,
    s_out_indices_ptr,
    s_out_logits_ptr,
    STEP: tl.constexpr,
    TOPK: tl.constexpr,
    HAS_TLE: tl.constexpr,
    CANONICAL_OUTPUT: tl.constexpr,
    MULTIPLE_BLOCKS_PER_ROW: tl.constexpr,
    MERGE_BLOCKS: tl.constexpr,
    found_count,
    final_count,
    equal_count,
):
    NUM_FINAL_ITEMS: tl.constexpr = 2048

    bin_idx, is_partial_match = _extract_bin_idx(
        logits,
        in_range,
        logit_pattern,
        STEP=STEP,
    )
    take_lt = is_partial_match & (bin_idx < threshold_bin_idx) & write_directly
    if HAS_TLE or CANONICAL_OUTPUT:
        out_pos_lt = tl.atomic_add(
            found_topk_values_ptrs,
            ones,
            mask=take_lt,
            sem="relaxed",
            scope="cta",
        )
    else:
        out_pos_lt, found_count = _stable_output_positions(found_count, take_lt)
    if MERGE_BLOCKS:
        indices = tl.load(
            indices_ptr + offs,
            mask=take_lt,
        )
        tl.store(
            s_out_indices_ptr + out_pos_lt,
            indices,
            mask=take_lt,
        )
    elif MULTIPLE_BLOCKS_PER_ROW:
        tl.store(
            s_out_indices_ptr + out_pos_lt,
            (offs + row_start).to(tl.int32),
            mask=take_lt,
        )
        tl.store(
            s_out_logits_ptr + out_pos_lt,
            logits,
            mask=take_lt,
        )
    else:
        tl.store(
            s_out_indices_ptr + out_pos_lt,
            offs.to(tl.int32),
            mask=take_lt,
        )

    if STEP < 3:
        if use_final:
            take_eq_final = is_partial_match & (bin_idx == threshold_bin_idx)
            if HAS_TLE or CANONICAL_OUTPUT:
                final_pos = tl.atomic_add(
                    final_cnt_ptrs,
                    ones,
                    mask=take_eq_final,
                    sem="relaxed",
                    scope="cta",
                )
            else:
                final_pos, final_count = _stable_output_positions(
                    final_count, take_eq_final
                )
            tl.store(
                s_final_logits_ptr + final_pos,
                logits,
                mask=take_eq_final & (final_pos < NUM_FINAL_ITEMS),
            )
            # s_histogram_ptr being used for indices in final sort
            if MERGE_BLOCKS:
                indices = tl.load(
                    indices_ptr + offs,
                    mask=take_eq_final & (final_pos < NUM_FINAL_ITEMS),
                )
                tl.store(
                    s_histogram_ptr + final_pos,
                    indices,
                    mask=take_eq_final & (final_pos < NUM_FINAL_ITEMS),
                )
            elif MULTIPLE_BLOCKS_PER_ROW:
                tl.store(
                    s_histogram_ptr + final_pos,
                    (offs + row_start).to(tl.int32),
                    mask=take_eq_final & (final_pos < NUM_FINAL_ITEMS),
                )
            else:
                tl.store(
                    s_histogram_ptr + final_pos,
                    offs.to(tl.int32),
                    mask=take_eq_final & (final_pos < NUM_FINAL_ITEMS),
                )
    else:
        take_eq = is_partial_match & (bin_idx == threshold_bin_idx)
        # s_histogram_ptr being used for exclude prefix sum
        if HAS_TLE:
            out_pos_eq = tl.atomic_add(
                s_histogram_ptr + bin_idx,
                ones,
                mask=take_eq,
                sem="relaxed",
                scope="cta",
            )
        else:
            out_pos_eq, equal_count = _stable_output_positions(equal_count, take_eq)
        if MERGE_BLOCKS:
            indices = tl.load(
                indices_ptr + offs,
                mask=take_eq & (out_pos_eq < TOPK),
            )
            tl.store(
                s_out_indices_ptr + out_pos_eq,
                indices,
                mask=take_eq & (out_pos_eq < TOPK),
            )
        elif MULTIPLE_BLOCKS_PER_ROW:
            tl.store(
                s_out_indices_ptr + out_pos_eq,
                (offs + row_start).to(tl.int32),
                mask=take_eq & (out_pos_eq < TOPK),
            )
            tl.store(
                s_out_logits_ptr + out_pos_eq,
                logits,
                mask=take_eq & (out_pos_eq < TOPK),
            )
        else:
            tl.store(
                s_out_indices_ptr + out_pos_eq,
                offs.to(tl.int32),
                mask=take_eq & (out_pos_eq < TOPK),
            )
    return found_count, final_count, equal_count


@triton.jit
def _process_histogram_step(
    logits_ptr,
    row_start,
    row_end,
    stride1,
    vocab_size,
    skip_elems,
    indices_ptr,
    logit_pattern,
    threshold_bin_idx,
    assume_aligned,
    s_histogram_ptr,
    s_final_logits_ptr,
    s_final_cnt_ptr,
    s_threshold_bin_idx_ptr,
    s_final_bin_size_ptr,
    s_found_topk_values_ptr,
    s_out_indices_ptr,
    s_out_logits_ptr,
    STEP: tl.constexpr,
    TOPK: tl.constexpr,
    BLOCK_SIZE: tl.constexpr,
    HAS_TLE: tl.constexpr,
    CANONICAL_OUTPUT: tl.constexpr,
    MULTIPLE_BLOCKS_PER_ROW: tl.constexpr,
    MERGE_BLOCKS: tl.constexpr,
):
    VEC: tl.constexpr = 4
    NUM_FINAL_ITEMS: tl.constexpr = 2048
    RADIX11_SIZE: tl.constexpr = 2048
    RADIX11_MASK: tl.constexpr = 0x7FF
    RADIX10_SIZE: tl.constexpr = 1024

    lane = tl.arange(0, BLOCK_SIZE)
    vec = tl.arange(0, VEC)
    ones = tl.full([BLOCK_SIZE], 1, tl.int32)
    ones_vec_2d = tl.full([BLOCK_SIZE, VEC], 1, tl.int32)
    zeros = tl.zeros([BLOCK_SIZE], dtype=tl.int32)
    zeros_vec_2d = tl.zeros([BLOCK_SIZE, VEC], dtype=tl.int32)

    threshold_rounds: tl.constexpr = (
        RADIX10_SIZE // BLOCK_SIZE if STEP == 3 else RADIX11_SIZE // BLOCK_SIZE
    )
    for clear_round in tl.static_range(0, threshold_rounds):
        clear_bins = clear_round * BLOCK_SIZE + lane
        tl.store(s_histogram_ptr + clear_bins, 0)
    tl.debug_barrier()

    if STEP == 2:
        logit_pattern = (threshold_bin_idx.to(tl.uint32) & RADIX11_MASK) << 21
    elif STEP == 3:
        logit_pattern |= (threshold_bin_idx.to(tl.uint32) & RADIX11_MASK) << 10

    if assume_aligned:
        n_tiles = tl.cdiv(vocab_size, BLOCK_SIZE)
        n_vec_full = vocab_size // (BLOCK_SIZE * VEC)
        rem_tiles = (vocab_size - n_vec_full * BLOCK_SIZE * VEC) // BLOCK_SIZE
        for t in tl.range(0, n_vec_full):
            base = t * BLOCK_SIZE * VEC + lane * VEC
            offs = base[:, None] + vec[None, :]
            x_vec = tl.load(logits_ptr + offs)
            _distribute_to_bins(
                x_vec,
                True,
                ones_vec_2d,
                logit_pattern,
                s_histogram_ptr,
                STEP=STEP,
            )
        for t in tl.range(0, rem_tiles):
            offs = (n_vec_full * VEC + t) * BLOCK_SIZE + lane
            x = tl.load(logits_ptr + offs)
            _distribute_to_bins(
                x,
                True,
                ones,
                logit_pattern,
                s_histogram_ptr,
                STEP=STEP,
            )
    elif stride1 == 1:
        aligned_row_ptr = tl.multiple_of(logits_ptr + row_start + skip_elems, VEC * 4)
        row_len = row_end - row_start - skip_elems
        n_vec_full = row_len // (BLOCK_SIZE * VEC)
        rem_tiles = (row_len - n_vec_full * BLOCK_SIZE * VEC) // BLOCK_SIZE
        rem_elems = row_len % BLOCK_SIZE
        for t in tl.range(0, n_vec_full):
            base = t * BLOCK_SIZE * VEC + lane * VEC
            offs = base[:, None] + vec[None, :]
            x_vec = tl.load(aligned_row_ptr + offs)
            _distribute_to_bins(
                x_vec,
                True,
                ones_vec_2d,
                logit_pattern,
                s_histogram_ptr,
                STEP=STEP,
            )
        for t in tl.range(0, rem_tiles):
            offs = (n_vec_full * VEC + t) * BLOCK_SIZE + lane
            x = tl.load(aligned_row_ptr + offs)
            _distribute_to_bins(
                x,
                True,
                ones,
                logit_pattern,
                s_histogram_ptr,
                STEP=STEP,
            )
        if skip_elems > 0:
            offs = lane
            in_range = lane < skip_elems
            x = tl.load(
                logits_ptr + row_start + offs, mask=in_range, other=float("-inf")
            )
            _distribute_to_bins(
                x,
                in_range,
                ones,
                logit_pattern,
                s_histogram_ptr,
                STEP=STEP,
            )
        if rem_elems > 0:
            offs = (n_vec_full * VEC + rem_tiles) * BLOCK_SIZE + lane
            in_range = lane < rem_elems
            x = tl.load(aligned_row_ptr + offs, mask=in_range, other=float("-inf"))
            _distribute_to_bins(
                x,
                in_range,
                ones,
                logit_pattern,
                s_histogram_ptr,
                STEP=STEP,
            )
    else:
        row_len = row_end - row_start
        n_tiles = tl.cdiv(row_len, BLOCK_SIZE)
        for t in tl.range(0, n_tiles):
            offs = t * BLOCK_SIZE + lane
            in_range = offs < row_len
            x = tl.load(
                logits_ptr + row_start + offs * stride1,
                mask=in_range,
                other=float("-inf"),
            )
            _distribute_to_bins(
                x,
                in_range,
                ones,
                logit_pattern,
                s_histogram_ptr,
                STEP=STEP,
            )
    last_value = tl.load(s_found_topk_values_ptr)
    tl.debug_barrier()

    threshold_bin_ptrs = s_threshold_bin_idx_ptr + zeros
    final_bin_size_ptrs = s_final_bin_size_ptr + zeros
    threshold_found = tl.full((), False, dtype=tl.int1)
    for round_idx in tl.static_range(0, threshold_rounds):
        if not threshold_found:
            bins = round_idx * BLOCK_SIZE + lane
            counts = tl.load(s_histogram_ptr + bins)
            if HAS_TLE:
                prefix_sum, counts_total = _exclusive_cumsum(counts)
            else:
                counts_total = tl.sum(counts)
                prefix_sum = counts_total - tl.cumsum(counts, axis=0, reverse=True)
            prefix_sum = prefix_sum + last_value
            total_sum = last_value + counts_total
            next_prefix_sum = prefix_sum + counts
            threshold_mask = (prefix_sum < TOPK) & (next_prefix_sum >= TOPK)
            threshold_bin = bins
            threshold_bin_size = next_prefix_sum - prefix_sum
            if STEP == 3:
                tl.store(s_histogram_ptr + bins, prefix_sum)
            tl.store(threshold_bin_ptrs, threshold_bin, mask=threshold_mask)
            tl.store(final_bin_size_ptrs, threshold_bin_size, mask=threshold_mask)
            found_round = tl.reduce_or(threshold_mask, axis=0)
            threshold_found = found_round
            last_value = total_sum

    tl.debug_barrier()
    threshold_bin_idx = tl.load(s_threshold_bin_idx_ptr)
    final_bin_size = tl.load(s_final_bin_size_ptr)
    use_final = final_bin_size <= NUM_FINAL_ITEMS
    write_directly = ((STEP == 0) & (final_bin_size <= NUM_FINAL_ITEMS)) | (STEP >= 1)

    found_count = tl.zeros((), tl.int32)
    final_count = tl.zeros((), tl.int32)
    equal_count = tl.zeros((), tl.int32)
    if not HAS_TLE:
        if not CANONICAL_OUTPUT:
            found_count = tl.load(s_found_topk_values_ptr)
            final_count = tl.load(s_final_cnt_ptr)
        if STEP == 3:
            equal_count = tl.load(s_histogram_ptr + threshold_bin_idx)

    found_ptrs = s_found_topk_values_ptr
    final_cnt_ptrs = s_final_cnt_ptr
    if HAS_TLE or CANONICAL_OUTPUT:
        found_ptrs = s_found_topk_values_ptr + zeros
        final_cnt_ptrs = s_final_cnt_ptr + zeros
    if assume_aligned:
        found_ptrs_vec_2d = s_found_topk_values_ptr
        final_cnt_ptrs_vec_2d = s_final_cnt_ptr
        if HAS_TLE or CANONICAL_OUTPUT:
            found_ptrs_vec_2d = s_found_topk_values_ptr + zeros_vec_2d
            final_cnt_ptrs_vec_2d = s_final_cnt_ptr + zeros_vec_2d
        n_tiles = tl.cdiv(vocab_size, BLOCK_SIZE)
        n_vec_full = vocab_size // (BLOCK_SIZE * VEC)
        rem_tiles = (vocab_size - n_vec_full * BLOCK_SIZE * VEC) // BLOCK_SIZE
        for t in tl.range(0, n_vec_full):
            base = t * BLOCK_SIZE * VEC + lane * VEC
            offs = base[:, None] + vec[None, :]
            x_vec = tl.load(logits_ptr + offs)
            found_count, final_count, equal_count = _process_bins(
                x_vec,
                True,
                ones_vec_2d,
                offs,
                found_ptrs_vec_2d,
                final_cnt_ptrs_vec_2d,
                logit_pattern,
                threshold_bin_idx,
                write_directly,
                use_final,
                row_start,
                indices_ptr,
                s_histogram_ptr,
                s_final_logits_ptr,
                s_out_indices_ptr,
                s_out_logits_ptr,
                STEP=STEP,
                TOPK=TOPK,
                HAS_TLE=HAS_TLE,
                CANONICAL_OUTPUT=CANONICAL_OUTPUT,
                found_count=found_count,
                final_count=final_count,
                equal_count=equal_count,
                MULTIPLE_BLOCKS_PER_ROW=MULTIPLE_BLOCKS_PER_ROW,
                MERGE_BLOCKS=MERGE_BLOCKS,
            )
        for t in tl.range(0, rem_tiles):
            offs = (n_vec_full * VEC + t) * BLOCK_SIZE + lane
            x = tl.load(logits_ptr + offs)
            found_count, final_count, equal_count = _process_bins(
                x,
                True,
                ones,
                offs,
                found_ptrs,
                final_cnt_ptrs,
                logit_pattern,
                threshold_bin_idx,
                write_directly,
                use_final,
                row_start,
                indices_ptr,
                s_histogram_ptr,
                s_final_logits_ptr,
                s_out_indices_ptr,
                s_out_logits_ptr,
                STEP=STEP,
                TOPK=TOPK,
                HAS_TLE=HAS_TLE,
                CANONICAL_OUTPUT=CANONICAL_OUTPUT,
                found_count=found_count,
                final_count=final_count,
                equal_count=equal_count,
                MULTIPLE_BLOCKS_PER_ROW=MULTIPLE_BLOCKS_PER_ROW,
                MERGE_BLOCKS=MERGE_BLOCKS,
            )
    elif stride1 == 1:
        found_ptrs_vec_2d = s_found_topk_values_ptr
        final_cnt_ptrs_vec_2d = s_final_cnt_ptr
        if HAS_TLE or CANONICAL_OUTPUT:
            found_ptrs_vec_2d = s_found_topk_values_ptr + zeros_vec_2d
            final_cnt_ptrs_vec_2d = s_final_cnt_ptr + zeros_vec_2d
        aligned_row_ptr = tl.multiple_of(logits_ptr + row_start + skip_elems, VEC * 4)
        row_len = row_end - row_start - skip_elems
        n_vec_full = row_len // (BLOCK_SIZE * VEC)
        rem_tiles = (row_len - n_vec_full * BLOCK_SIZE * VEC) // BLOCK_SIZE
        rem_elems = row_len % BLOCK_SIZE
        if not HAS_TLE and skip_elems > 0:
            offs = lane
            in_range = lane < skip_elems
            x = tl.load(
                logits_ptr + row_start + offs, mask=in_range, other=float("-inf")
            )
            found_count, final_count, equal_count = _process_bins(
                x,
                in_range,
                ones,
                offs,
                found_ptrs,
                final_cnt_ptrs,
                logit_pattern,
                threshold_bin_idx,
                write_directly,
                use_final,
                row_start,
                indices_ptr,
                s_histogram_ptr,
                s_final_logits_ptr,
                s_out_indices_ptr,
                s_out_logits_ptr,
                STEP=STEP,
                TOPK=TOPK,
                HAS_TLE=HAS_TLE,
                CANONICAL_OUTPUT=CANONICAL_OUTPUT,
                found_count=found_count,
                final_count=final_count,
                equal_count=equal_count,
                MULTIPLE_BLOCKS_PER_ROW=MULTIPLE_BLOCKS_PER_ROW,
                MERGE_BLOCKS=MERGE_BLOCKS,
            )
        for t in tl.range(0, n_vec_full):
            base = t * BLOCK_SIZE * VEC + lane * VEC
            offs = base[:, None] + vec[None, :]
            x_vec = tl.load(aligned_row_ptr + offs)
            found_count, final_count, equal_count = _process_bins(
                x_vec,
                True,
                ones_vec_2d,
                offs + skip_elems,
                found_ptrs_vec_2d,
                final_cnt_ptrs_vec_2d,
                logit_pattern,
                threshold_bin_idx,
                write_directly,
                use_final,
                row_start,
                indices_ptr,
                s_histogram_ptr,
                s_final_logits_ptr,
                s_out_indices_ptr,
                s_out_logits_ptr,
                STEP=STEP,
                TOPK=TOPK,
                HAS_TLE=HAS_TLE,
                CANONICAL_OUTPUT=CANONICAL_OUTPUT,
                found_count=found_count,
                final_count=final_count,
                equal_count=equal_count,
                MULTIPLE_BLOCKS_PER_ROW=MULTIPLE_BLOCKS_PER_ROW,
                MERGE_BLOCKS=MERGE_BLOCKS,
            )
        for t in tl.range(0, rem_tiles):
            offs = (n_vec_full * VEC + t) * BLOCK_SIZE + lane
            x = tl.load(aligned_row_ptr + offs)
            found_count, final_count, equal_count = _process_bins(
                x,
                True,
                ones,
                offs + skip_elems,
                found_ptrs,
                final_cnt_ptrs,
                logit_pattern,
                threshold_bin_idx,
                write_directly,
                use_final,
                row_start,
                indices_ptr,
                s_histogram_ptr,
                s_final_logits_ptr,
                s_out_indices_ptr,
                s_out_logits_ptr,
                STEP=STEP,
                TOPK=TOPK,
                HAS_TLE=HAS_TLE,
                CANONICAL_OUTPUT=CANONICAL_OUTPUT,
                found_count=found_count,
                final_count=final_count,
                equal_count=equal_count,
                MULTIPLE_BLOCKS_PER_ROW=MULTIPLE_BLOCKS_PER_ROW,
                MERGE_BLOCKS=MERGE_BLOCKS,
            )
        if HAS_TLE and skip_elems > 0:
            offs = lane
            in_range = lane < skip_elems
            x = tl.load(
                logits_ptr + row_start + offs, mask=in_range, other=float("-inf")
            )
            found_count, final_count, equal_count = _process_bins(
                x,
                in_range,
                ones,
                offs,
                found_ptrs,
                final_cnt_ptrs,
                logit_pattern,
                threshold_bin_idx,
                write_directly,
                use_final,
                row_start,
                indices_ptr,
                s_histogram_ptr,
                s_final_logits_ptr,
                s_out_indices_ptr,
                s_out_logits_ptr,
                STEP=STEP,
                TOPK=TOPK,
                HAS_TLE=HAS_TLE,
                CANONICAL_OUTPUT=CANONICAL_OUTPUT,
                found_count=found_count,
                final_count=final_count,
                equal_count=equal_count,
                MULTIPLE_BLOCKS_PER_ROW=MULTIPLE_BLOCKS_PER_ROW,
                MERGE_BLOCKS=MERGE_BLOCKS,
            )
        if rem_elems > 0:
            offs = (n_vec_full * VEC + rem_tiles) * BLOCK_SIZE + lane
            in_range = lane < rem_elems
            x = tl.load(aligned_row_ptr + offs, mask=in_range, other=float("-inf"))
            found_count, final_count, equal_count = _process_bins(
                x,
                in_range,
                ones,
                offs + skip_elems,
                found_ptrs,
                final_cnt_ptrs,
                logit_pattern,
                threshold_bin_idx,
                write_directly,
                use_final,
                row_start,
                indices_ptr,
                s_histogram_ptr,
                s_final_logits_ptr,
                s_out_indices_ptr,
                s_out_logits_ptr,
                STEP=STEP,
                TOPK=TOPK,
                HAS_TLE=HAS_TLE,
                CANONICAL_OUTPUT=CANONICAL_OUTPUT,
                found_count=found_count,
                final_count=final_count,
                equal_count=equal_count,
                MULTIPLE_BLOCKS_PER_ROW=MULTIPLE_BLOCKS_PER_ROW,
                MERGE_BLOCKS=MERGE_BLOCKS,
            )
    else:
        row_len = row_end - row_start
        n_tiles = tl.cdiv(row_len, BLOCK_SIZE)
        for t in tl.range(0, n_tiles):
            offs = t * BLOCK_SIZE + lane
            in_range = offs < row_len
            x = tl.load(
                logits_ptr + row_start + offs * stride1,
                mask=in_range,
                other=float("-inf"),
            )
            found_count, final_count, equal_count = _process_bins(
                x,
                in_range,
                ones,
                offs,
                found_ptrs,
                final_cnt_ptrs,
                logit_pattern,
                threshold_bin_idx,
                write_directly,
                use_final,
                row_start,
                indices_ptr,
                s_histogram_ptr,
                s_final_logits_ptr,
                s_out_indices_ptr,
                s_out_logits_ptr,
                STEP=STEP,
                TOPK=TOPK,
                HAS_TLE=HAS_TLE,
                CANONICAL_OUTPUT=CANONICAL_OUTPUT,
                found_count=found_count,
                final_count=final_count,
                equal_count=equal_count,
                MULTIPLE_BLOCKS_PER_ROW=MULTIPLE_BLOCKS_PER_ROW,
                MERGE_BLOCKS=MERGE_BLOCKS,
            )
    if not HAS_TLE:
        if not CANONICAL_OUTPUT:
            tl.store(s_found_topk_values_ptr, found_count)
            tl.store(s_final_cnt_ptr, final_count)
        if STEP == 3:
            tl.store(s_histogram_ptr + threshold_bin_idx, equal_count)
    tl.debug_barrier()
    return final_bin_size > NUM_FINAL_ITEMS, logit_pattern, threshold_bin_idx


@triton.jit
def _top_k_per_row_job(
    logits_ptr,
    out_indices_ptr,
    row_start,
    row_end,
    stride1,
    vocab_size,
    skip_elems,
    out_logits_ptr,
    indices_ptr,
    s_histogram_ptr,
    s_final_logits_ptr,
    s_final_cnt_ptr,
    s_threshold_bin_idx_ptr,
    s_final_bin_size_ptr,
    s_found_topk_values_ptr,
    s_out_indices_ptr,
    s_out_logits_ptr,
    TOPK: tl.constexpr,
    BLOCK_SIZE: tl.constexpr,
    USE_RADIX_FINAL: tl.constexpr,
    HAS_TLE: tl.constexpr,
    CANONICAL_OUTPUT: tl.constexpr,
    MULTIPLE_BLOCKS_PER_ROW: tl.constexpr,
    MERGE_BLOCKS: tl.constexpr,
    ABS_INDICES: tl.constexpr,
):
    NUM_FINAL_ITEMS: tl.constexpr = 2048

    # Triton specializes integer args equal to 1 as constexpr (e.g. vocab_size
    # when S == 1); constexpr has no shape, so tl.multiple_of fails. Adding a
    # 0-d tensor keeps it a runtime scalar; the +0 folds away for normal shapes.
    vocab_size = vocab_size + tl.zeros((), dtype=tl.int32)

    assume_aligned = (
        (row_start == 0)
        & (row_end == vocab_size)
        & (stride1 == 1)
        & ((vocab_size % BLOCK_SIZE) == 0)
    )
    if assume_aligned:
        tl.assume(row_start == 0)
        tl.assume(row_end == vocab_size)
        tl.assume(stride1 == 1)
        vocab_size = tl.multiple_of(vocab_size, BLOCK_SIZE)
    elif stride1 == 1:
        tl.assume(stride1 == 1)

    lane = tl.arange(0, BLOCK_SIZE)
    row_len = row_end - row_start
    if row_len <= TOPK:
        chunks: tl.constexpr = (TOPK + BLOCK_SIZE - 1) // BLOCK_SIZE
        for chunk_idx in tl.range(0, chunks):
            pos = chunk_idx * BLOCK_SIZE + lane
            take_row = pos < row_len
            if MULTIPLE_BLOCKS_PER_ROW:
                tl.store(
                    out_indices_ptr + pos,
                    (pos + row_start).to(tl.int32),
                    mask=take_row,
                )
                logits = tl.load(logits_ptr + pos + row_start, mask=take_row)
                tl.store(out_logits_ptr + pos, logits, mask=take_row)
            elif ABS_INDICES:
                tl.store(
                    out_indices_ptr + pos,
                    (pos + row_start).to(tl.int32),
                    mask=take_row,
                )
            else:
                tl.store(
                    out_indices_ptr + pos,
                    pos.to(tl.int32),
                    mask=take_row,
                )
            take_pad = (pos >= row_len) & (pos < TOPK)
            tl.store(out_indices_ptr + pos, -1, mask=take_pad)
            if MULTIPLE_BLOCKS_PER_ROW:
                tl.store(out_logits_ptr + pos, float("-inf"), mask=take_pad)
        return
    tl.store(s_final_cnt_ptr, 0)
    tl.store(s_found_topk_values_ptr, 0)
    tl.debug_barrier()
    logit_pattern = tl.zeros((), dtype=tl.uint32)
    continue_to_next_step = tl.full((), True, dtype=tl.int1)
    threshold_bin_idx = tl.full((), -1, dtype=tl.int32)
    for step_idx in tl.static_range(0, 4):
        if continue_to_next_step:
            (
                continue_to_next_step,
                logit_pattern,
                threshold_bin_idx,
            ) = _process_histogram_step(
                logits_ptr,
                row_start,
                row_end,
                stride1,
                vocab_size,
                skip_elems,
                indices_ptr,
                logit_pattern,
                threshold_bin_idx,
                assume_aligned,
                s_histogram_ptr,
                s_final_logits_ptr,
                s_final_cnt_ptr,
                s_threshold_bin_idx_ptr,
                s_final_bin_size_ptr,
                s_found_topk_values_ptr,
                s_out_indices_ptr,
                s_out_logits_ptr,
                STEP=step_idx,
                TOPK=TOPK,
                BLOCK_SIZE=BLOCK_SIZE,
                HAS_TLE=HAS_TLE,
                CANONICAL_OUTPUT=CANONICAL_OUTPUT,
                MULTIPLE_BLOCKS_PER_ROW=MULTIPLE_BLOCKS_PER_ROW,
                MERGE_BLOCKS=MERGE_BLOCKS,
            )

    if not continue_to_next_step:
        if USE_RADIX_FINAL and HAS_TLE:
            _final_select_rank(
                s_histogram_ptr,
                s_final_logits_ptr,
                s_final_cnt_ptr,
                s_found_topk_values_ptr,
                s_out_indices_ptr,
                s_out_logits_ptr,
                TOPK=TOPK,
                BLOCK_SIZE=BLOCK_SIZE,
                MULTIPLE_BLOCKS_PER_ROW=MULTIPLE_BLOCKS_PER_ROW,
            )
        else:
            base_idx = tl.load(s_found_topk_values_ptr)
            # Guard against stale/oversized counts to avoid out-of-bounds accesses
            # in the shared-memory final buffers.
            final_cnt = tl.minimum(tl.load(s_final_cnt_ptr), NUM_FINAL_ITEMS)
            sort_chunks = tl.cdiv(final_cnt, BLOCK_SIZE)
            for sort_chunk in tl.range(0, sort_chunks):
                pos = sort_chunk * BLOCK_SIZE + lane
                valid = pos < final_cnt
                logit_i = tl.load(
                    s_final_logits_ptr + pos,
                    mask=valid,
                    other=0,
                )
                out_rank = tl.zeros([BLOCK_SIZE], dtype=tl.int32)
                if not HAS_TLE and (CANONICAL_OUTPUT or MERGE_BLOCKS):
                    original_i = tl.load(s_histogram_ptr + pos, mask=valid, other=0)
                for j in tl.range(0, final_cnt):
                    logit_j = tl.load(s_final_logits_ptr + j)
                    if HAS_TLE:
                        better = (logit_i < logit_j) | (
                            (logit_i == logit_j) & (pos < j)
                        )
                    elif CANONICAL_OUTPUT or MERGE_BLOCKS:
                        original_j = tl.load(s_histogram_ptr + j)
                        better = (logit_i < logit_j) | (
                            (logit_i == logit_j) & (original_i > original_j)
                        )
                    else:
                        # Stable collection visits original indices in order.
                        better = (logit_i < logit_j) | (
                            (logit_i == logit_j) & (pos > j)
                        )
                    out_rank = out_rank + (valid & better).to(tl.int32)
                dst_pos = base_idx + out_rank
                take = valid & (dst_pos < TOPK)
                idx_i = tl.load(
                    s_histogram_ptr + pos,
                    mask=take,
                    other=0,
                )
                tl.store(s_out_indices_ptr + dst_pos, idx_i, mask=take)
                if MULTIPLE_BLOCKS_PER_ROW:
                    tl.store(s_out_logits_ptr + dst_pos, logit_i, mask=take)
            tl.debug_barrier()

    if not HAS_TLE and CANONICAL_OUTPUT:
        # Atomic collection can reorder an otherwise identical selected set.
        SORT_SIZE: tl.constexpr = triton.next_power_of_2(TOPK)
        positions = tl.arange(0, SORT_SIZE)
        selected = tl.load(
            out_indices_ptr + positions, mask=positions < TOPK, other=0x7FFFFFFF
        )
        ordered = tl.sort(selected, descending=False)
        tl.store(out_indices_ptr + positions, ordered, mask=positions < TOPK)

    # out_indices_ptr is identical to s_out_indices_ptr for non-tle
    if HAS_TLE:
        flush_chunks: tl.constexpr = (TOPK + BLOCK_SIZE - 1) // BLOCK_SIZE
        for flush_chunk in tl.static_range(flush_chunks):
            pos = flush_chunk * BLOCK_SIZE + lane
            mask = pos < TOPK
            out_vals = tl.load(s_out_indices_ptr + pos, mask=mask, other=-1)
            if ABS_INDICES:
                out_vals = tl.where(out_vals >= 0, out_vals + row_start, out_vals)
            tl.store(out_indices_ptr + pos, out_vals, mask=mask)
            if MULTIPLE_BLOCKS_PER_ROW:
                split_logits = tl.load(
                    s_out_logits_ptr + pos, mask=mask, other=float("-inf")
                )
                tl.store(out_logits_ptr + pos, split_logits, mask=mask)


# End of shared implementation code for top_k_per_row_decode and top_k_per_row_prefill


@triton.jit
def kernel_tle_bucket_sort_topk(
    logits_ptr,
    out_indices_ptr,
    row_starts,
    row_ends,
    stride0,
    stride1,
    vocab_size,
    TOPK: tl.constexpr,
    TOPKP: tl.constexpr,
    BLOCK_SIZE: tl.constexpr,
    USE_RADIX_FINAL: tl.constexpr,
    ABS_INDICES: tl.constexpr,
    ROW_OFFSET: tl.constexpr,
):
    NUM_FILNAL_ITEMS: tl.constexpr = 2048
    NUM_BINS: tl.constexpr = 2048
    VEC: tl.constexpr = 4

    row_id = tl.program_id(0) + ROW_OFFSET
    row_start = tl.load(row_starts + row_id).to(tl.int32)
    row_end = tl.load(row_ends + row_id).to(tl.int32)
    logits_ptr += row_id * stride0
    # float4 align
    x_off_mod = (row_id * stride0 + row_start) % VEC
    skip_elems = 0 if x_off_mod == 0 else VEC - x_off_mod
    out_indices_ptr += row_id * TOPK

    # used for histogram, indices in final sort and exclude prefix_sum
    s_histogram = tle.gpu.alloc(
        [NUM_BINS],
        dtype=tl.int32,
        layout=None,
        scope=tle.gpu.smem,
        nv_mma_shared_layout=False,
    )
    s_final_logits = tle.gpu.alloc(
        [NUM_FILNAL_ITEMS],
        dtype=tl.float32,
        layout=None,
        scope=tle.gpu.smem,
        nv_mma_shared_layout=False,
    )
    s_out_indices = tle.gpu.alloc(
        [TOPKP],
        dtype=tl.int32,
        layout=None,
        scope=tle.gpu.smem,
        nv_mma_shared_layout=False,
    )
    s_final_cnt = tle.gpu.alloc(
        [1],
        dtype=tl.int32,
        layout=None,
        scope=tle.gpu.smem,
        nv_mma_shared_layout=False,
    )
    s_threshold_bin_idx = tle.gpu.alloc(
        [1],
        dtype=tl.int32,
        layout=None,
        scope=tle.gpu.smem,
        nv_mma_shared_layout=False,
    )
    s_final_bin_size = tle.gpu.alloc(
        [1],
        dtype=tl.int32,
        layout=None,
        scope=tle.gpu.smem,
        nv_mma_shared_layout=False,
    )
    s_found_topk_values = tle.gpu.alloc(
        [1],
        dtype=tl.int32,
        layout=None,
        scope=tle.gpu.smem,
        nv_mma_shared_layout=False,
    )
    s_histogram_ptr = tle.gpu.local_ptr(s_histogram, (0,))
    s_final_logits_ptr = tle.gpu.local_ptr(s_final_logits, (0,))
    s_out_indices_ptr = tle.gpu.local_ptr(s_out_indices, (0,))
    s_final_cnt_ptr = tle.gpu.local_ptr(s_final_cnt, (0,))
    s_threshold_bin_idx_ptr = tle.gpu.local_ptr(s_threshold_bin_idx, (0,))
    s_final_bin_size_ptr = tle.gpu.local_ptr(s_final_bin_size, (0,))
    s_found_topk_values_ptr = tle.gpu.local_ptr(s_found_topk_values, (0,))

    _top_k_per_row_job(
        logits_ptr,
        out_indices_ptr,
        row_start,
        row_end,
        stride1,
        vocab_size,
        skip_elems,
        None,
        None,
        s_histogram_ptr,
        s_final_logits_ptr,
        s_final_cnt_ptr,
        s_threshold_bin_idx_ptr,
        s_final_bin_size_ptr,
        s_found_topk_values_ptr,
        s_out_indices_ptr,
        None,
        TOPK=TOPK,
        BLOCK_SIZE=BLOCK_SIZE,
        USE_RADIX_FINAL=USE_RADIX_FINAL,
        HAS_TLE=True,
        CANONICAL_OUTPUT=False,
        MULTIPLE_BLOCKS_PER_ROW=False,
        MERGE_BLOCKS=False,
        ABS_INDICES=ABS_INDICES,
    )



# MetaX TLE shim (algorithm from FlagGems-vllm's MetaX shim, inlined here; flaggems_vllm is not imported at runtime)
_MAX_THREADS = 512
WIDE_TILE_VOCAB = 16384


@triton.jit
def _cumsum_exclusive(x, axis: tl.constexpr = 0, reverse: tl.constexpr = False):
    """Exclusive prefix sum and total, implemented with plain tl ops."""
    tl.static_assert(not reverse, "reverse=True is not implemented")
    return tl.cumsum(x, axis=axis) - x, tl.sum(x, axis=axis)


@triton.jit
def _final_select_rank(
    s_histogram_ptr,
    s_final_logits_ptr,
    s_final_cnt_ptr,
    s_found_topk_values_ptr,
    s_out_indices_ptr,
    s_out_logits_ptr,
    TOPK: tl.constexpr,
    BLOCK_SIZE: tl.constexpr,
    MULTIPLE_BLOCKS_PER_ROW: tl.constexpr,
):
    """Non-radix final selection: rank loop.

    The radix variant is wrong and slower on C550.
    """
    NUM_FINAL_ITEMS: tl.constexpr = 2048
    lane = tl.arange(0, BLOCK_SIZE)
    base_idx = tl.load(s_found_topk_values_ptr)
    final_cnt = tl.minimum(tl.load(s_final_cnt_ptr), NUM_FINAL_ITEMS)
    sort_chunks = tl.cdiv(final_cnt, BLOCK_SIZE)
    for sort_chunk in tl.range(0, sort_chunks):
        pos = sort_chunk * BLOCK_SIZE + lane
        valid = pos < final_cnt
        logit_i = tl.load(s_final_logits_ptr + pos, mask=valid, other=0)
        out_rank = tl.zeros([BLOCK_SIZE], dtype=tl.int32)
        for j in tl.range(0, final_cnt):
            logit_j = tl.load(s_final_logits_ptr + j)
            better = (logit_i < logit_j) | ((logit_i == logit_j) & (pos < j))
            out_rank = out_rank + (valid & better).to(tl.int32)
        dst_pos = base_idx + out_rank
        take = valid & (dst_pos < TOPK)
        idx_i = tl.load(s_histogram_ptr + pos, mask=take, other=0)
        tl.store(s_out_indices_ptr + dst_pos, idx_i, mask=take)
        if MULTIPLE_BLOCKS_PER_ROW:
            tl.store(s_out_logits_ptr + dst_pos, logit_i, mask=take)
    tl.debug_barrier()


def _build_shim():
    if not HAS_TLE:
        return None
    real = tle.gpu

    # Constant-zero pid >> 31: the MetaX plugin widens shared-memory reads based
    # on pointer alignment and asserts below 4 elements/thread. It must be a
    # builtin (TLE buffers cannot be passed to @jit functions).
    @tl.core.builtin
    def local_ptr(buffer, indices=None, _semantic=None, _generator=None):
        p = real.local_ptr(buffer, indices, _semantic=_semantic, _generator=_generator)
        pid = tl.program_id(0, _semantic=_semantic)
        return p.__add__(pid.__rshift__(31, _semantic=_semantic), _semantic=_semantic)

    gpu = types.ModuleType("bin_topk_tle_gpu")
    for name, value in vars(real).items():
        if not name.startswith("__"):
            setattr(gpu, name, value)
    gpu.local_ptr = local_ptr
    shim = types.ModuleType("bin_topk_tle")
    shim.gpu = gpu
    shim.cumsum = _cumsum_exclusive
    return shim


_SHIM = _build_shim()
if _SHIM is not None:
    tle = _SHIM
    _warp, _maxt = _launch_geometry()
    _LAUNCH_GEOMETRY = (_warp, min(_maxt, _MAX_THREADS))


def _tile_size(vocab_size):
    """Tile width: 1024 for long rows, 512 for short rows (see ledgers/tuning-decisions.md)."""
    return 1024 if vocab_size >= WIDE_TILE_VOCAB else 512


def tle_bucket_sort_topk(inputs, starts, ends, topk):
    """TLE variant (same name as FlagGems bin_topk.py): absolute indices, with
    -1 padding when a row is shorter than topk.

    inputs: [B, S] fp32 (supports stride0 padding, stride1 == 1)
    starts/ends: [B] int32, valid row range [start, end)
    """
    # Match upstream: validate inputs and cast non-fp32 inputs to float32.
    # torch.empty is safe: the kernel writes every slot in [0, topk) on both
    # paths, so pre-filling with -1 only adds an extra B*topk*4-byte write.
    if not HAS_TLE:
        raise NotImplementedError("TLE is unavailable; v3 implements only the TLE path")
    if inputs.ndim != 2:
        raise ValueError("inputs must be a 2D tensor")
    if starts.ndim != 1 or ends.ndim != 1:
        raise ValueError("starts and ends must be 1D tensors")
    inputs = inputs.float() if inputs.dtype != torch.float32 else inputs
    num_rows, vocab_size = inputs.shape
    out = torch.empty((num_rows, topk), dtype=torch.int32, device=inputs.device)

    block = _tile_size(vocab_size)
    num_warps = _num_warps(block)
    topkp = triton.next_power_of_2(topk)
    # Kept upstream name (USE_RADIX_FINAL): it only chooses between calling
    # _final_select_rank and inlining the same rank loop.
    use_radix_final = _use_radix_final_for_prefill(vocab_size)
    num_insert_sort_blocks = (
        0 if use_radix_final else min(num_rows, SORTING_ALGORITHM_THRESHOLD)
    )
    if num_insert_sort_blocks > 0:
        kernel_tle_bucket_sort_topk[(num_insert_sort_blocks,)](
            inputs,
            out,
            starts,
            ends,
            inputs.stride(0),
            inputs.stride(1),
            vocab_size,
            TOPK=topk,
            TOPKP=topkp,
            BLOCK_SIZE=block,
            USE_RADIX_FINAL=False,
            ABS_INDICES=True,
            ROW_OFFSET=0,
            num_warps=num_warps,
        )
    if num_rows > num_insert_sort_blocks:
        kernel_tle_bucket_sort_topk[(num_rows - num_insert_sort_blocks,)](
            inputs,
            out,
            starts,
            ends,
            inputs.stride(0),
            inputs.stride(1),
            vocab_size,
            TOPK=topk,
            TOPKP=topkp,
            BLOCK_SIZE=block,
            USE_RADIX_FINAL=True,
            ABS_INDICES=True,
            ROW_OFFSET=num_insert_sort_blocks,
            num_warps=num_warps,
        )
    return out


