def _make_case(batch, seq_len, topk, pad=7, partial=False, seed=0):
    """Build inputs with stride0 padding; partial=True uses non-zero starts/ends.

    Elements outside [start, end) are set to 1e9 so an out-of-range read is
    caught by the multiset check.
    """
    torch.manual_seed(seed)
    buf = torch.randn((batch, seq_len + pad), device="cuda", dtype=torch.float32)
    x = buf.as_strided((batch, seq_len), (seq_len + pad, 1))
    if partial:
        starts = torch.randint(0, max(1, seq_len // 4), (batch,), dtype=torch.int32, device="cuda")
        ends = torch.minimum(
            starts + torch.randint(1, max(2, seq_len // 2), (batch,), dtype=torch.int32, device="cuda"),
            torch.full((batch,), seq_len, dtype=torch.int32, device="cuda"),
        )
    else:
        starts = torch.zeros(batch, dtype=torch.int32, device="cuda")
        ends = torch.full((batch,), seq_len, dtype=torch.int32, device="cuda")
    for b in range(batch):
        st, en = int(starts[b]), int(ends[b])
        x[b, :st] = 1e9
        x[b, en:] = 1e9
    return x, starts, ends, topk


def _check_case(x, starts, ends, topk, tag):
    out = dsa_bucket_topk(x, starts, ends, topk)
    torch.cuda.synchronize()
    assert out.shape == (x.shape[0], topk), (tag, out.shape)
    for b in range(x.shape[0]):
        st, en = int(starts[b]), int(ends[b])
        row = x[b, st:en]
        n = min(topk, row.numel())
        want = torch.topk(row, n).values

        o = out[b]
        idx = o[o >= 0].long()
        pad = o[o < 0]
        assert idx.numel() == n, f"{tag} row {b}: valid indices {idx.numel()} != {n}"
        assert pad.numel() == topk - n, f"{tag} row {b}: -1 count {pad.numel()} != {topk - n}"
        assert bool((pad == -1).all()), f"{tag} row {b}: padding value is not -1"
        if idx.numel():
            assert int(idx.min()) >= st and int(idx.max()) < en, (
                f"{tag} row {b}: index out of range [{int(idx.min())},{int(idx.max())}) vs [{st},{en})"
            )
        got = torch.sort(x[b, idx], descending=True).values
        assert torch.equal(got, want), f"{tag} row {b}: selected-value multiset mismatch"
    print(f"[PASS] {tag}: B={x.shape[0]} S={x.shape[1]} K={topk}")


# 13 acceptance cases: 7 official + 6 upstream fixed-starts / small-forward cases.
BENCH_CASES = (
    (64, 129280, 1024, 129280, "DeepSeek V4", "official"),
    (4, 8193, 512, 8456, "V4-Flash", "official"),
    (16383, 4095, 512, 4352, "huge batch", "official"),
    (4, 16385, 512, 16648, "", "official"),
    (12961, 4100, 512, 4360, "", "official"),
    (16380, 5115, 512, 5376, "", "official"),
    (4100, 1025, 512, 1288, "", "official"),
    (3, 1024, 32, 1024, "fixed starts=[0,0,0]", "fixed0"),
    (3, 1024, 32, 1024, "fixed starts=[7,31,63]", "fixed7"),
    (1, 256, 16, 256, "forward B=1 S=256 K=16", "upstream"),
    (1, 256, 64, 256, "forward B=1 S=256 K=64", "upstream"),
    (1, 256, 256, 256, "forward B=1 S=256 K=256", "upstream"),
    (1, 1024, 16, 1024, "forward B=1 S=1024 K=16", "upstream"),
)
GATE = 0.95


def _official_inputs(batch, seq_len, stride0):
    torch.manual_seed(42)
    buf = torch.randn((batch - 1) * stride0 + seq_len, device="cuda", dtype=torch.float32)
    x = torch.as_strided(buf, (batch, seq_len), (stride0, 1))
    starts = torch.zeros(batch, dtype=torch.int32, device="cuda")
    ends = torch.full((batch,), seq_len, dtype=torch.int32, device="cuda")
    return x, starts, ends


def _fixed_inputs(batch, seq_len, start_list, end_list):
    torch.manual_seed(1234)
    x = torch.randn((batch, seq_len), device="cuda", dtype=torch.float32)
    starts = torch.tensor(start_list, dtype=torch.int32, device="cuda")
    ends = torch.tensor(end_list, dtype=torch.int32, device="cuda")
    return x, starts, ends


def _upstream_inputs(batch, seq_len):
    torch.manual_seed(1234)
    x = torch.randn((batch, seq_len), device="cuda", dtype=torch.float32)
    starts = torch.zeros(batch, dtype=torch.int32, device="cuda")
    ends = torch.randint(
        max(1, seq_len // 2), seq_len + 1, (batch,), dtype=torch.int32, device="cuda"
    )
    return x, starts, ends


def _load_maca():
    """Optionally load the MetaX native baseline; returns None if mcoplib is missing."""
    import contextlib
    import io

    try:
        with contextlib.redirect_stdout(io.StringIO()):  # mcoplib prints a version banner
            import mcoplib._C  # noqa: F401

        return torch.ops._C.top_k_per_row_prefill
    except Exception:
        return None


def _run_maca(op, x, starts, ends, topk):
    # Same as bench3: the native op writes row-relative indices; return absolute.
    out = torch.empty((x.shape[0], topk), dtype=torch.int32, device=x.device)
    op(x, starts, ends, out, x.shape[0], x.stride(0), x.stride(1), topk)
    return out + starts[:, None]


def _bench_all(args):
    import os

    import triton.testing

    op = _load_maca()
    if op is None:
        print("!! MACA native op not available (mcoplib); maca column will be '-'")

    suite = "all"
    print(
        f"tle impl: bin_topk_tle | suite: {suite} ({len(BENCH_CASES)} cases) | "
        f"device: MACA_VISIBLE_DEVICES={os.environ.get('MACA_VISIBLE_DEVICES', '<unset>')} "
        f"(visible={torch.cuda.device_count()}, {torch.cuda.get_device_name(0)})"
    )
    print(
        f"{'B':>6} {'S':>7} {'K':>5} {'s0':>7} | {'tle':>9} {'maca':>9}"
        f" | {'tle/maca':>8} {'gate':>6}"
    )

    ratios = []
    passed = 0
    for batch, seq_len, topk, stride0, desc, kind in BENCH_CASES:
        if kind == "official":
            x, starts, ends = _official_inputs(batch, seq_len, stride0)
        elif kind == "fixed0":
            x, starts, ends = _fixed_inputs(batch, seq_len, [0, 0, 0], [512, 768, 1024])
        elif kind == "fixed7":
            x, starts, ends = _fixed_inputs(batch, seq_len, [7, 31, 63], [700, 900, 1024])
        else:
            x, starts, ends = _upstream_inputs(batch, seq_len)

        tle_ms = maca_ms = None
        try:
            tle_ms = triton.testing.do_bench(
                lambda: dsa_bucket_topk(x, starts, ends, topk),
                warmup=args.warmup,
                rep=args.rep,
            )
        except Exception as exc:  # noqa: BLE001
            print(f"!! TLE {batch}x{seq_len}: {type(exc).__name__}: {str(exc).splitlines()[0][:80]}")
        if op is not None:
            try:
                maca_ms = triton.testing.do_bench(
                    lambda: _run_maca(op, x, starts, ends, topk),
                    warmup=args.warmup,
                    rep=args.rep,
                )
            except Exception as exc:  # noqa: BLE001
                print(f"!! MACA {batch}x{seq_len}: {type(exc).__name__}: {str(exc).splitlines()[0][:80]}")

        tle_txt = "-" if tle_ms is None else f"{tle_ms:.4f}"
        maca_txt = "-" if maca_ms is None else f"{maca_ms:.4f}"
        if tle_ms is None:
            ratio_txt, gate = "-", "FAIL"
        elif maca_ms is None:
            ratio_txt, gate = "-", "SKIP"
        else:
            ratio = maca_ms / tle_ms
            ratios.append(ratio)
            ok = ratio >= GATE
            passed += int(ok)
            ratio_txt, gate = f"{ratio:.1%}", "PASS" if ok else "FAIL"
        print(
            f"{batch:>6} {seq_len:>7} {topk:>5} {x.stride(0):>7} | "
            f"{tle_txt:>9} {maca_txt:>9} | {ratio_txt:>8} {gate:>6}"
            + (f"  # {desc}" if desc else "")
        )

    if ratios:
        geo = 1.0
        for ratio in ratios:
            geo *= ratio
        geo **= 1.0 / len(ratios)
        print(f"[{suite}] pass {passed}/{len(ratios)} (threshold {GATE:.0%}), geomean {geo:.1%}")
    return 0


def main(argv=None):
    import argparse

    parser = argparse.ArgumentParser(
        description="dsa_bucket_topk self-check / 13-case TLE vs MACA comparison"
    )
    parser.add_argument("--batch", type=int, default=None)
    parser.add_argument("--seq-len", type=int, default=None)
    parser.add_argument("--topk", type=int, default=None)
    parser.add_argument("--bench", action="store_true", help="13-case TLE vs MACA")
    parser.add_argument("--warmup", type=int, default=25)
    parser.add_argument("--rep", type=int, default=100)
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args(argv)

    if not torch.cuda.is_available():
        raise SystemExit("CUDA/MACA device required")
    if args.bench:
        return _bench_all(args)
    if args.batch or args.seq_len or args.topk:
        cases = [(args.batch or 4, args.seq_len or 8193, args.topk or 512, True)]
    else:
        cases = [
            (4, 8193, 512, True),
            (3, 4095, 512, True),
            (2, 1025, 128, True),
            (1, 7, 16, False),
        ]

    for i, (batch, seq_len, topk, partial) in enumerate(cases):
        x, starts, ends, k = _make_case(
            batch, seq_len, topk, partial=partial, seed=args.seed + i
        )
        _check_case(x, starts, ends, k, f"case{i}")

    print("ALL PASS")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

