def source_graph_hash(module):
    """Validation fingerprint only; do not alter the compiler's actual proposal."""
    ids = {p.id for p in module.selection_points if p.kind == "distribution"}
    logical = replace(module, stage="unused_functions_removed",
                      metadata={k: v for k, v in module.metadata.items() if k != "auto_distribution_proposal"},
                      selection_points=tuple(p for p in module.selection_points if p.id not in ids),
                      selections=tuple(r for r in module.selections if r.point_id not in ids))
    return logical.semantic_hash


