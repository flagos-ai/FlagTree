"""A43 fixed96 channel ownership on the existing canonical convolution ABI.

The implementation replaces the existing target entry in-place. Its parameters,
variant and facts are regenerated by ordinary selection; graph types are intact.
"""
from dataclasses import replace
from pathlib import Path
import os

from triton.flagmega.codegen.triton.candidates import TritonCandidateProviderRegistry
from triton.flagmega.codegen.triton.candidates.gdn_head_gates import _broadcast, _shape, _dense
from triton.flagmega.codegen.triton.implementation import TritonImplementationModel
from triton.flagmega.codegen.triton.selection import TritonTirSelectionPolicy
from triton.flagmega.errors import CodegenError
from triton.flagmega.ir import DType, RefType, VectorType

IMPLEMENTATION = "tir.gdn_convolution.persistent"
VARIANT = "canonical_channel128_fixed96"
OVERRIDE = "llama-short-token128-bf16-packed8-fixed96-v1"
ATTRS = dict(accumulation_order="current_first", conv_kernel_size=4,
             round_before_activation=True, round_products=True)
PARAMS = dict(tile_channels=128, num_warps=4, channel128_override=OVERRIDE,
              channel_owner="128*blockIdx.x+threadIdx.x", physical_ctas=96,
              active_ctas=80, channels=10240, state_channel_pack=8)


def require(ok, detail):
    if not ok:
        raise CodegenError("A43 canonical channel128: " + detail)


def applicable(node, context):
    out = node.type.fields[0]
    p = getattr(out, "placement", None)
    if (context.codegen_backend != "cpp" or not context.cooperative_grid
            or getattr(context.target, "name", None) != "nvidia-sm120"
            or os.environ.get("FLAGMEGA_CPP_BLOCK_THREADS", "128") != "128"
            or p is None or p.hierarchy != (4, 24) or p.hierarchy_levels != "bb"
            or dict(node.attrs) != ATTRS):
        return False
    source, state, weight = (context.module.node_map[i].type for i in node.inputs)
    if (source != out or not _broadcast(out, p, (1, 10240), DType.BFLOAT16)
            or not _broadcast(weight, p, (10240, 1, 4), DType.FLOAT32)
            or not isinstance(state, RefType) or node.type.fields[1] != state):
        return False
    leaf = dict(state.fields).get("convolution")
    return (leaf is not None and _shape(leaf) == (1, 1280, 3) and _dense(leaf)
            and leaf.dtype == VectorType(DType.BFLOAT16, (8,)))


class Provider:
    def __init__(self, original):
        self.original, self.op_names = original, original.op_names

    def propose(self, node, context):
        if node.op == "nn.gdn_convolution":
            require(applicable(node, context), "requires exact CPP SM120 fixed4x24 BF16/F32/packed8 contract")
        result = self.original.propose(node, context)
        if node.op == "nn.gdn_convolution":
            require(result is not None and result.default_candidate == IMPLEMENTATION,
                    "ordinary provider did not select requested override")
        return result


def buffer(raw, direction, formal, leaf=0):
    return next(x for x in raw[direction] if x["formal"] == formal)["buffers"][leaf]


def validate_raw(raw):
    require(raw["implementation"] == IMPLEMENTATION and raw["variant"] == VARIANT,
            "wrong selected implementation/variant")
    require(all(raw["parameters"].get(k) == v for k, v in PARAMS.items()), "stale selected parameters")
    require(dict(raw["semantic_attrs"]) == ATTRS, "numeric contract changed")
    require(not raw["workspaces"] and not raw["shared_workspaces"], "unexpected scratch")
    q, w, o = buffer(raw, "inputs", "qkv"), buffer(raw, "inputs", "conv_weight"), buffer(raw, "outputs", "result_0")
    s, so = buffer(raw, "inputs", "state"), buffer(raw, "outputs", "result_1")
    for b, shape, stride, scalar, lanes, storage in (
            (q, (1,10240), (10240,1), "bfloat16", (), "workspace"),
            (o, (1,10240), (10240,1), "bfloat16", (), "workspace"),
            (w, (10240,1,4), (4,4,1), "float32", (), "parameter"),
            (s, (1,1280,3), (30720,24,8), "bfloat16", (8,), "parameter")):
        a = b["abi"]
        require(a["coordinate_space"] == "canonical_global" and a["memory_sharing_scope"] == "chip"
                and a["storage"] == storage and a["scalar_dtype"] == scalar
                and tuple(a["logical_shape"]) == shape and tuple(a["local_capacity_shape"]) == shape
                and tuple(a["scalar_storage_strides"]) == stride and tuple(a["scalar_lane_shape"]) == lanes
                and not a.get("component_stride_elements") and not a.get("component_stride_scalar_elements")
                and not a.get("pool_scope_stride_bytes") and not a.get("owner_stride_bytes")
                and a.get("distributed_backing_type") is None, "noncanonical or incompatible " + b["formal"])
        require(tuple(a["active_shape_expressions"]) == tuple(str(v) for v in shape)
                and tuple(a["logical_coordinate_expressions"]) == tuple(f"local_coord_{i}" for i in range(len(shape)))
                and tuple(a["storage_coordinate_expressions"]) == tuple(f"local_coord_{i}" for i in range(len(shape))),
                "nonidentity scalar coordinate map")
        if b is not s:
            d = a["distributed_type"]
            require(a["storage_kind"] == "canonical_global" and d is not None
                    and tuple(d["placement"]["hierarchy"]) == (4,24)
                    and d["placement"]["hierarchy_levels"] == "bb"
                    and not d["partial"] and not d["exclusive"]
                    and all(x["kind"] == "broadcast" for x in d["axis_policies"]), "nonreplicated graph ABI")
        else:
            require(a["storage_kind"] == "compact_local" and a["owner_count"] == 1
                    and a["distributed_type"] is None and a["physical_buffer"].startswith("external:")
                    and b["runtime_argument"] != "block_local_data", "state root is private")
    view = s["abi"].get("view_byte_offset", {})
    require(view.get("op") == "mul" and len(view.get("operands", ())) == 2
            and view["operands"][1] == {"kind":"fixed", "value":61440}
            and view["operands"][0].get("kind") == "symbolic"
            and view["operands"][0].get("minimum") == 0
            and view["operands"][0].get("maximum") == 47, "state layer slice changed")
    require(s["actual"] == so["actual"] and s["abi"] == so["abi"]
            and s["runtime_argument"] == so["runtime_argument"], "state update aliases differ")
    require(buffer(raw,"inputs","state",1)["abi"] == buffer(raw,"outputs","result_1",1)["abi"],
            "recurrent passthrough alias changed")
    require(q["runtime_argument"] == o["runtime_argument"] == "workspace", "workspace base substituted")
    qb, ob = q["abi"]["pool_byte_offset"], o["abi"]["pool_byte_offset"]
    require(qb + 20480 <= ob or ob + 20480 <= qb, "QKV and result spans overlap")
    return {"schema":"flagmega.conv-channel-owner/v1", "override":OVERRIDE,
            "channel":"128*blockIdx.x+threadIdx.x", "guard":"channel<10240",
            "grid":[96,1,1], "block_threads":128, "active_ctas":80,
            "qkv":q, "result":o, "state":s, "state_output":so, "weight":w,
            "state_scalar_offset":"24*(channel//8)+8*history+channel%8"}


def validate_context(context):
    calls = [c for c in context["render_calls"] if c["family"] == "gdn_convolution"]
    if calls:
        require(context["platform"] == "nvidia" and context["target_architecture"] == "sm120"
                and context["block_threads"] == 128 and context["warp_size"] == 32
                and tuple(context["grid"]) == (96,1,1), "physical launch changed")
        require(len(calls) == len(context["render_calls"]) == 1, "convolution must retain separate publication")
        for c in calls:
            require(c.get("channel128_override") == OVERRIDE and c.get("channel_owner_contract"), "encoder not selected")
    return [c["channel_owner_contract"] for c in calls]


def enable():
    from triton.flagmega.targets import get_target
    from triton.flagmega.codegen.triton import kernel_call_renderers as encoders, tir_package
    from jinja2 import ChoiceLoader, FileSystemLoader
    target = get_target("nvidia-sm120")
    model, policy = target.triton_implementation_model, target.tir_selection_policy
    require(isinstance(policy, TritonTirSelectionPolicy), "requires ordinary selection policy")
    old = model.implementation(IMPLEMENTATION)
    require(old is not None and old.variant == "persistent", "override already installed or parent changed")
    new = replace(old, variant=VARIANT, parameters={**dict(old.parameters),**PARAMS},
                  contract={**dict(old.contract),"required_codegen_backend":"cpp","canonical_channel_owner":OVERRIDE},
                  facts={**dict(old.facts),"canonical_channel_owner":OVERRIDE,"unique_state_writers":True})
    target.triton_implementation_model = TritonImplementationModel(
        tuple(new if x.id == IMPLEMENTATION else x for x in model.implementations), model.preferences,
        model.name + "+conv-channel128-fixed96-v1")
    registry = TritonCandidateProviderRegistry(); changed = 0
    for p in policy.registry.providers:
        if "nn.gdn_convolution" in p.op_names:
            p = Provider(p); changed += 1
        registry.add(p)
    require(changed == 1, "ambiguous convolution provider")
    target.tir_selection_policy = TritonTirSelectionPolicy(policy.workspace_annotator, registry)
    original = encoders._FAMILY_ENCODERS["gdn_convolution"]
    def encode(raw):
        owner = validate_raw(raw)
        result = original(raw)
        # The original per-operand pointer/offset algebra is deliberately kept.
        # Explicit disjoint channel ownership replaces broadcast representative election.
        result.update(channel128_override=OVERRIDE, channel_owner_contract=owner,
                      writer_active="local_channels < 10240")
        return result
    encoders._FAMILY_ENCODERS["gdn_convolution"] = encode
    root = Path(__file__).parent / "tir_metadata"
    class MetadataRegistry(tir_package.TritonTemplateRegistry):
        def __init__(self):
            super().__init__()
            self.environment.loader = ChoiceLoader([FileSystemLoader(str(root)),self.environment.loader])
        def resolve(self, spec):
            if (spec.kernel,spec.variant,spec.platform,spec.architecture) == ("gdn_convolution",VARIANT,"nvidia","sm120"):
                return "kernels/gdn_convolution/canonical_channel128_fixed96.py.jinja"
            return super().resolve(spec)
    tir_package.TritonTemplateRegistry = MetadataRegistry
