  gold=json.loads((W/'.local/milestones/m000/revisions/r000/measurements/r000-r4-20261116T103555Z/golden'/scenario/'metadata.json').read_text())
  prompt=gold['input_tokens'][:gold['prompt_token_count']];start=max(0,len(prompt)-1)
  save(dest/'loaded-identity.json',[dict(name=p.compiled_kernel.name,cubin_sha256=hashlib.sha256(p.compiled_kernel.asm['cubin']).hexdigest(),grid=list(p.grid),metadata=p.compiled_kernel.metadata._asdict()) for p in c.runtime._prepared])
  def trajectory(kind):
   c.reset();tokens=[]
   for step in range(steps):
    if step<len(prompt):c.values['input_ids'].fill_(prompt[step])
    c.launch() if kind=='eager' else c.graph.replay()
    tokens.append(int(c.token.item()))
   return tokens,c.snapshot(steps-1)
  tokens,endpoint=trajectory('eager')
  assert tokens[start:start+10]==gold['tokens'][start:start+10]
  c.capture();warm,pre=trajectory('graph');assert warm==tokens and pre==endpoint
  save(dest/'pre.json',dict(tokens=tokens,endpoint=endpoint,MODEL_TOKEN10='PASS'))
  active_check();c.reset();latency=[];actual=[];window_start=time.monotonic_ns()
  for step in range(steps):
   if step<len(prompt):c.values['input_ids'].fill_(prompt[step])
   c.stream.synchronize()
   before=time.perf_counter_ns();c.graph.replay();token=int(c.token.item());after=time.perf_counter_ns()
   latency.append(after-before);actual.append(token)
  raw=dict(pid=os.getpid(),arm=arm,scenario=scenario,round=r,steps=steps,start_ns=window_start,end_ns=time.monotonic_ns(),latency_ns=latency,tokens=actual,profiler_attached=False,boundary='ordinary CUDA graph replay + GPU greedy + CPU token return')
