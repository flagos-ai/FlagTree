def _implementation(
    candidate_id: str,
    family: str,
    variant: str,
    parameters=None,
    *,
    contract=None,
    requires=(),
    facts=None,
    shared_workspaces=(),
    transfer_pipeline=None,
) -> TritonImplementation:
    return TritonImplementation(
        candidate_id,
        family,
        variant,
        parameters or {},
        contract or {},
        requires,
        facts or {},
        align_shared_workspaces(shared_workspaces),
        transfer_pipeline,
    )


